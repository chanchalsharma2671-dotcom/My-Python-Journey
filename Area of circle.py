# 1.We take a diameter from the user
Diameter  = float(input("Enter the diameter of circle :"))
# 2.and convert into Radius
Radius = Diameter/2
# 3.and execute the formula of area of a circle in a variable
Area = 3.14*(Radius**2)
#4.and then print the area of circle
print(f"The area of circle is {Area}")

a = float(input("Enter your 1st number : "))
b = float(input("Enter your 2nd number : "))
c = input("Enter your operation : ")
if c== "+":
    print(a+b)
elif c== "-":
    print(a-b)
elif c== "*":
    print(a*b)
elif c== "/":
    print(a/b)
else :
    print("The operation you enter is incorrect")
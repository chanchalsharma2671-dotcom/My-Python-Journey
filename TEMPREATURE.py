# 1. Variables holding the input values
celsius_temp = 25
fahrenheit_temp = 77

# 2. Variable operations calculating the conversion
converted_to_fahrenheit = (celsius_temp * 9/5) + 32
converted_to_celsius = (fahrenheit_temp - 32) * 5/9

# 3. Simple printing of the results
print("Celsius to Fahrenheit:")
print(converted_to_fahrenheit)

print("Fahrenheit to Celsius:")
print(converted_to_celsius)
